// Package load generates the k6 script for a run. Load is always open
// model (ramping-arrival-rate): arrivals follow the profile whether or not
// the system keeps up, so a slow system can't hide its latency by slowing
// the generator down.
package load

import (
	"bytes"
	"encoding/json"
	"fmt"
	"text/template"

	"github.com/akinfemi/load-lore/internal/plan"
)

// SummaryPath is where the script writes k6's end-of-test summary inside
// the load generator container.
const SummaryPath = "/tmp/k6-summary.json"

type stage struct {
	Target   float64 `json:"target"`
	Duration string  `json:"duration"`
}

type params struct {
	URLs         []string  `json:"urls"`
	StartRate    float64   `json:"startRate"`
	Stages       []stage   `json:"stages"`
	ReadShare    float64   `json:"readShare"`
	PayloadBytes int       `json:"payloadBytes"`
	Keys         plan.Keys `json:"keys"`
	PreVUs       int       `json:"preVUs"`
	MaxVUs       int       `json:"maxVUs"`
	Timeout      string    `json:"timeout"`
	Seed         int64     `json:"seed"`
	Scatter      int64     `json:"scatter"`
}

// Script returns the k6 script for a plan's workload.
func Script(p *plan.Plan) ([]byte, error) {
	w := p.Workload
	pr := params{
		URLs: w.URLs, StartRate: w.StartRate, ReadShare: w.ReadShare, PayloadBytes: w.PayloadBytes,
		Keys: w.Keys, PreVUs: w.PreVUs, MaxVUs: w.MaxVUs, Timeout: fmt.Sprintf("%dms", w.Timeout.D().Milliseconds()),
		Seed: p.Seed, Scatter: scatterFor(w.Keys.Count),
	}
	for _, s := range w.Stages {
		pr.Stages = append(pr.Stages, stage{Target: s.Target, Duration: fmt.Sprintf("%ds", int64(s.Duration.D().Seconds()))})
	}
	data, err := json.MarshalIndent(pr, "", "  ")
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	err = scriptTmpl.Execute(&b, map[string]any{"Params": string(data), "Name": p.Name, "RunID": p.RunID, "Summary": SummaryPath})
	return b.Bytes(), err
}

// scatterFor picks a multiplier coprime with n, so rank r maps to key
// (r-1)*m mod n + 1: hot ranks land on keys spread across the table
// instead of the first pages.
func scatterFor(n int64) int64 {
	for _, m := range []int64{1000003, 1000033, 1000037, 1000039} {
		if gcd(m, n) == 1 {
			return m
		}
	}
	return 1
}

func gcd(a, b int64) int64 {
	for b != 0 {
		a, b = b, a%b
	}
	return a
}

var scriptTmpl = template.Must(template.New("k6").Parse(`// Generated by loadl for run {{.RunID}} ({{.Name}}). Do not edit: the run
// folder's design.yaml is the source of truth.
import http from 'k6/http';
import exec from 'k6/execution';

const P = {{.Params}};

export const options = {
  discardResponseBodies: true,
  // Keep metric series bounded: every request URL carries its key, so the
  // url tag would make one series per key.
  systemTags: ['status', 'method', 'name', 'scenario', 'expected_response', 'error_code'],
  summaryTrendStats: ['avg', 'min', 'med', 'p(90)', 'p(95)', 'p(99)', 'max'],
  scenarios: {
    load: {
      executor: 'ramping-arrival-rate',
      startRate: P.startRate,
      timeUnit: '1s',
      preAllocatedVUs: P.preVUs,
      maxVUs: P.maxVUs,
      stages: P.stages,
    },
  },
};

// Randomness. With a seed, each iteration draws from its own generator
// seeded by (seed, iteration number), so the sequence of keys and request
// types is the same on every run whichever VU runs an iteration.
let rand = Math.random;
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function seedIteration(i) {
  if (!P.seed) return;
  rand = mulberry32(Math.imul(P.seed | 0, 0x9E3779B1) ^ Math.imul(i | 0, 0x85EBCA77));
}

// Keys: rank 1 is the hottest; scatter maps ranks onto keys spread across
// the table.
const N = P.keys.count;
function scatter(rank) { return ((rank - 1) * P.scatter) % N + 1; }

// Zipf sampling by rejection-inversion (Hörmann and Derflinger, 1996).
const S = P.keys.skew || 1;
function helper1(x) { return Math.abs(x) > 1e-8 ? Math.log1p(x) / x : 1 - x * (0.5 - x * (1 / 3 - 0.25 * x)); }
function helper2(x) { return Math.abs(x) > 1e-8 ? Math.expm1(x) / x : 1 + x * 0.5 * (1 + x * (1 / 3) * (1 + 0.25 * x)); }
function hIntegral(x) { const l = Math.log(x); return helper2((1 - S) * l) * l; }
function h(x) { return Math.exp(-S * Math.log(x)); }
function hIntegralInverse(x) { let t = x * (1 - S); if (t < -1) t = -1; return Math.exp(helper1(t) * x); }
const hX1 = hIntegral(1.5) - 1;
const hN = hIntegral(N + 0.5);
const sZ = 2 - hIntegralInverse(hIntegral(2.5) - h(2));
function zipfRank() {
  for (;;) {
    const u = hN + rand() * (hX1 - hN);
    const x = hIntegralInverse(u);
    let k = Math.floor(x + 0.5);
    if (k < 1) k = 1; else if (k > N) k = N;
    if (k - x <= sZ || u >= hIntegral(k + 0.5) - h(k)) return k;
  }
}

function nextKey() {
  switch (P.keys.distribution) {
    case 'zipf':
      return scatter(zipfRank());
    case 'hotspot': {
      const hot = Math.max(1, Math.floor(P.keys.fraction * N));
      if (hot >= N || rand() < P.keys.share) return scatter(1 + Math.floor(rand() * hot));
      return scatter(hot + 1 + Math.floor(rand() * (N - hot)));
    }
    default:
      return 1 + Math.floor(rand() * N);
  }
}

const body = 'x'.repeat(P.payloadBytes);
const readParams = { timeout: P.timeout, tags: { name: 'read' } };
const writeParams = { timeout: P.timeout, tags: { name: 'write' } };

export default function () {
  const i = exec.scenario.iterationInTest;
  seedIteration(i);
  const url = P.urls[i % P.urls.length];
  const key = nextKey();
  if (rand() < P.readShare) {
    http.get(url + '/r?type=read&key=' + key, readParams);
  } else {
    http.post(url + '/r?type=write&key=' + key, body, writeParams);
  }
}

export function handleSummary(data) {
  return { '{{.Summary}}': JSON.stringify(data) };
}
`))
